/**
 * Build the shared English fallback used by the translated locales.
 *
 * 15 components used to do `import enPages from '../../i18n/locales/en/pages.json'`
 * so an untranslated page could fall back to English. Because that import is
 * static, it dragged the ENTIRE ~3.1 MB English copy of the site into the main
 * bundle — every visitor, in every language, downloaded all of it.
 *
 * Almost none of it was needed. Only two things are:
 *
 *   1. Top-level keys a locale does not have at all. Every translated locale is
 *      missing the same set today, so one shared file serves all six and is
 *      cached once rather than duplicated per language.
 *   2. The three destination-hub keys. Those exist in every locale, but
 *      DestinationHub/DestinationsPage deliberately read the ENGLISH item names
 *      and descriptions as a per-card fallback, so the English copy has to ship
 *      even when the locale has its own.
 *
 * Everything else — the ~246 keys every locale does translate — is dead weight
 * and is excluded.
 *
 * Written to src/i18n/locales/en-fallback.json, committed so `npm run dev`
 * works from a clean checkout, and regenerated by `npm run build` so it can
 * never drift from the locale files.
 *
 *   node scripts/generate-en-fallback.js
 */

import { readFileSync, statSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const LOCALES = join(__dirname, '..', 'src', 'i18n', 'locales')
const TRANSLATED = ['de', 'fr', 'es', 'nl', 'cs', 'pl']

// Read the English item names/descriptions even when the locale has its own.
const HUB_KEYS = ['destinationsCities', 'destinationsRegions', 'destinationsPlaces']

const read = (lang) => JSON.parse(readFileSync(join(LOCALES, lang, 'pages.json'), 'utf-8'))

const en = read('en')
const missing = new Set()
const perLocale = {}
for (const lang of TRANSLATED) {
  const keys = Object.keys(read(lang))
  const own = new Set(keys)
  const gaps = Object.keys(en).filter((k) => !own.has(k))
  perLocale[lang] = gaps.length
  gaps.forEach((k) => missing.add(k))
}

const keys = [...new Set([...missing, ...HUB_KEYS])].filter((k) => k in en)
// Preserve the English file's own key order so the diff stays readable.
const ordered = Object.keys(en).filter((k) => keys.includes(k))
const out = {}
for (const k of ordered) out[k] = en[k]

const target = join(LOCALES, 'en-fallback.json')
writeFileSync(target, JSON.stringify(out, null, 2) + '\n', 'utf-8')

// Report from the files on disk rather than Buffer.byteLength — this project's
// eslint config only provides browser globals.
const kb = (p) => (statSync(p).size / 1024).toFixed(1)
console.log(`English fallback: ${ordered.length} of ${Object.keys(en).length} keys, `
  + `${kb(target)} KB (full English pages.json ${kb(join(LOCALES, 'en', 'pages.json'))} KB)`)
for (const lang of TRANSLATED) console.log(`   ${lang}: ${perLocale[lang]} untranslated keys`)
console.log(`   + ${HUB_KEYS.length} hub keys always included (per-card English fallback)`)
console.log(`wrote src/i18n/locales/en-fallback.json`)
